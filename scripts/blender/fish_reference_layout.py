def bind_reference(spec):
    """Give the existing armature authoring code the new anatomical sections."""
    art=LAYOUT[spec['id']]
    spec['_reference']=art
    ox,oy=art['origin']
    spec['profile']=[((ox-x)/200,width/200,(bottom-top)/400,
                      (oy-(top+bottom)*.5)/200)
                     for x,top,bottom,width in reversed(art['body'])]
    return spec
